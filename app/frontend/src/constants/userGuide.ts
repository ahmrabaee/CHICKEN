/** Find the guide section that documents a given app path (contextual help). */
export function guideSectionForPath(path: string): GuideSection | undefined {
  // longest/most-specific route match first
  const matches = USER_GUIDE.filter((s) =>
    s.routes.some((r) => (r === '/' ? path === '/' : path === r || path.startsWith(r + '/'))),
  );
  return matches.sort(
    (a, b) =>
      Math.max(...b.routes.map((r) => r.length)) - Math.max(...a.routes.map((r) => r.length)),
  )[0];
}
